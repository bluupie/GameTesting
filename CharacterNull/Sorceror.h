//This is just a write out for expectations of the sorceror class..
// The sorceror is going to be an int based character using wands, sceptres and staffs as a primary weapon.

// sorceror Weapons
    // Wand
        // Wands will have high cast speed times with lower added damage to spells and spell damage rolls available.
        // Wands will have the defensive layer of using a shield.
        // Wands wll focus on clear speed with faster time to cast spells and the ability to weave in and out of combat.
    // Sceptre
        // Sceptres are the middle ground item, requiring strength as well to mesh with the templar class.
        // Sceptres have a mid range cast speed base as well as mid range added damage to spells and spell damage rolls.
        // Sceptres will have access to shields.
        // Sceptres are the expected all rounder variant, mid range clear speed with mid range single target.
    // Staff
        // Staffs will have the lower end rolls of cast speed, but damage added to sells and spell damage will be the highest rolls.
        // Staffs will be more so focused on the high damage out put rather than the survivability of a wand or sceptre as those will have access to shields
        // Staffs will focus on moer single target damage.

    // Sorceror Gear
    // Sorceror will focus on energyshield, with either a mix of evasion or armour, but is not necessary to have a reasonable amount of survivability.
    // Sorceror will focus on caster modifiers which can only be found on caster weapons as well as energy shield (or es hybrid gear).
    // Sorcerors will gain additional power for mana-forged jewwls, that can be socketed into gear to grant additonal minor modifiers to cast type stats.
        // These include but are not limited to :
            // Increased Cast Speed,
            // Increased Mana,
            // Increased Spell Damage,
            // Increased Flat Damage to Seplls, etc....
    
    
    
